#!/usr/bin/env python3
"""
UC12 — Report + LinkedIn post generator
Reads latest benchmark JSON, fills report-template and linkedin-template.

Usage: python3 scripts/generate_report.py
"""
import json
import datetime
from pathlib import Path
from openai import OpenAI

BASE = Path(__file__).parent.parent
RUNS = BASE / "output" / "runs"
SOCIAL = BASE / "output" / "social-media"
SOCIAL.mkdir(exist_ok=True)

client = OpenAI(base_url="http://localhost:11434/v1", api_key="ollama")

def load_latest_summary():
    summaries = sorted(RUNS.glob("*-summary.json"), reverse=True)
    if not summaries:
        print("No summary JSON found. Run run_benchmark.py first.")
        raise SystemExit(1)
    with open(summaries[0]) as f:
        return json.load(f), summaries[0]

def build_benchmark_text(data):
    lines = ["Category results (median score /5):"]
    for cat, scores in data["results"].items():
        best = max(scores, key=scores.get)
        line = f"  {cat}: " + ", ".join(f"{m.split(':')[0]}={s}" for m,s in scores.items())
        line += f"  ← best: {best.split(':')[0]}"
        lines.append(line)
    lines.append(f"\nOverall totals: " + ", ".join(f"{m.split(':')[0]}={t}" for m,t in data["totals"].items()))
    lines.append(f"Winner: {data['winner'].split(':')[0]} ({data['totals'][data['winner']]}/{len(data['results'])*5})")
    return "\n".join(lines)

def call(model, system, user):
    r = client.chat.completions.create(
        model=model,
        messages=[{"role":"system","content":system},{"role":"user","content":user}],
        temperature=0.7, max_tokens=800,
    )
    return r.choices[0].message.content.strip()

def generate_linkedin(benchmark_text, winner):
    system = (
        "You are a B2B content strategist writing for ResearchReady on LinkedIn. "
        "Lead with the most counterintuitive finding. Include specific numbers. "
        "End with one question to drive comments. 150-250 words. "
        "No 'excited to share', no 'thrilled to announce', no em-dashes. Data-first."
    )
    user = (
        f"Write a LinkedIn post using these benchmark results:\n\n{benchmark_text}\n\n"
        f"Company: ResearchReady — an AI platform that builds and evaluates use cases.\n"
        f"Audience: AI practitioners, tech leaders, potential enterprise clients.\n"
        f"Angle: We ran this on real local hardware (RTX 4060, AMD Ryzen 7). "
        f"The repo is public — anyone can reproduce it."
    )
    return call(winner, system, user)

def generate_report_section(benchmark_text, winner):
    system = (
        "Write a concise 3-paragraph research report section. "
        "Paragraph 1: what was tested. Paragraph 2: key findings with data. "
        "Paragraph 3: practical implications for model selection. "
        "Formal but readable. No bullet points."
    )
    user = f"Write the report section for this benchmark:\n\n{benchmark_text}"
    return call(winner, system, user)

def main():
    data, path = load_latest_summary()
    print(f"Loaded: {path}")

    benchmark_text = build_benchmark_text(data)
    winner = data["winner"]
    date = data["date"]

    print(f"Generating report section with {winner}...")
    report = generate_report_section(benchmark_text, winner)

    print(f"Generating LinkedIn post with {winner}...")
    post = generate_linkedin(benchmark_text, winner)

    # Save
    report_path = SOCIAL / f"{date}-report-section.md"
    post_path = SOCIAL / f"{date}-linkedin-post.md"

    report_path.write_text(
        f"# ResearchReady AI Benchmark Report — {date}\n\n"
        f"_Generated by {winner} from UC12 benchmark results_\n\n"
        f"## Benchmark Summary\n\n```\n{benchmark_text}\n```\n\n"
        f"## Report Section\n\n{report}\n"
    )

    post_path.write_text(
        f"# LinkedIn Post Draft — {date}\n\n"
        f"_Generated by {winner} — review before posting_\n\n"
        f"---\n\n{post}\n\n"
        f"---\n\n**Repo:** https://github.com/Research-Ready/uc12-chainforge-eval\n"
    )

    print(f"\nReport: {report_path}")
    print(f"LinkedIn post: {post_path}")
    print("\n── LINKEDIN POST PREVIEW ──\n")
    print(post)

if __name__ == "__main__":
    main()
